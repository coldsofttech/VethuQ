"""Remove local cache/build clutter from the repo root.

    uv run python scripts/dev/cleanup.py

Deletes, if present: .mypy_cache, .pytest_cache, .ruff_cache, build, dist, and every __pycache__
folder under the root (the virtual environment, node_modules and .git are left alone).
All are gitignored and safely regenerated by the next lint/test/build run.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path


class Cleanup:
    """Removes local cache/build directories from a repository root."""

    REPO_ROOT = Path(__file__).resolve().parents[2]
    TARGETS = (".mypy_cache", ".pytest_cache", ".ruff_cache", "build", "dist")
    BYTECODE_DIRNAME = "__pycache__"
    SKIP_DIRNAMES = (".git", ".venv", "node_modules")  # never searched for __pycache__

    def __init__(
        self,
        root: Path = REPO_ROOT,
        targets: tuple[str, ...] = TARGETS,
    ) -> None:
        self.root = root
        self.targets = targets

    def run(self) -> None:
        for name in self.targets:
            self._remove(self.root / name)
        self._remove_bytecode()

    def _remove_bytecode(self) -> None:
        """Delete every `__pycache__` under the root, except inside the skipped folders."""
        found: list[Path] = []
        for folder, subfolders, _files in os.walk(self.root):
            subfolders[:] = [name for name in subfolders if name not in self.SKIP_DIRNAMES]
            if self.BYTECODE_DIRNAME in subfolders:
                subfolders.remove(self.BYTECODE_DIRNAME)  # no need to look inside
                found.append(Path(folder) / self.BYTECODE_DIRNAME)
        for path in found:
            shutil.rmtree(path, ignore_errors=True)
        if found:
            print(f"removed {len(found)} {self.BYTECODE_DIRNAME} folder(s)")

    @staticmethod
    def _remove(path: Path) -> None:
        if path.exists():
            shutil.rmtree(path)
            print(f"removed {path}")
        else:
            print(f"skipped {path} (not present)")


if __name__ == "__main__":
    Cleanup().run()
