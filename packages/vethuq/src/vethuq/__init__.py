class Sources:
    """Register and manage files/folders as OCR/indexing sources.

    Not instantiated directly — use `Vethuq().sources`.
    """

    def add(self, path: str | Path, *, languages: str | Sequence[str] | None = None) -> Source:
        """Register a file or folder as a source. Folders are indexed recursively.

        `languages` names the OCR languages its files are read in (`"te"`, `"en,te"`,
        `["en", "te"]` or `"auto"`; several are detected between). Left out, the
        `settings.ocr.languages` setting applies.

        Re-adding a path that was previously removed reactivates it instead
        of failing. Raises `SourcePathError` if `path` doesn't exist,
        `SourceAlreadyExistsError` if it's already an active source, and
        `UnknownLanguageError` for a language that doesn't exist.
        """
        storage = _open_storage()
        try:
            return _Sources.add(storage, path, languages=languages)
        finally:
            storage.close()

    def set_languages(
        self, path_or_id: str | Path | int, languages: str | Sequence[str] | None
    ) -> Source:
        """Choose the OCR languages a source's files are read in; None goes back to the setting.

        Applies to files indexed from now on; files already indexed keep what they have until
        they are re-indexed (`index.reindex(..., languages=...)`). Raises
        `SourceNotFoundError` if no active source matches and `UnknownLanguageError` for a
        language that doesn't exist.
        """
        storage = _open_storage()
        try:
            return _Sources.set_languages(storage, _Sources.coerce(path_or_id), languages)
        finally:
            storage.close()

    # Defined before `list` below, whose name would otherwise shadow the builtin in annotations.
    def files(self, path_or_id: str | Path | int) -> list[SourceFile]:
        """Return the files tracked under a source, by id or path, ordered by file path.

        Each `SourceFile` carries its id, status and the same detail
        `vethuq source list <source> --detail` shows. Raises
        `SourceNotFoundError` if no active source matches.
        """
        storage = _open_storage()
        try:
            return _Sources.list_files(storage, path_or_id)
        finally:
            storage.close()

    def list(self, include_inactive: bool = False) -> list[Source]:
        """Return registered sources, most recently added first."""
        storage = _open_storage()
        try:
            return _Sources.list_all(storage, include_inactive)
        finally:
            storage.close()

    def remove(self, path_or_id: str | Path | int) -> Source:
        """Unregister a source by id or path. Raises `SourceNotFoundError` if it doesn't exist."""
        storage = _open_storage()
        try:
            return _Sources.remove(storage, path_or_id)
        finally:
            storage.close()

    def purge(self, path_or_id: str | Path | int) -> PurgeResult:
        """Permanently delete a removed source (by id or path) or a removed file (by path).

        Works whether or not the retention period has passed, and deletes the
        indexed data too. Raises `SourceNotRemovedError` if the source or file is
        still active, and `SourceNotFoundError` if nothing matches.
        """
        storage = _open_storage()
        try:
            return _Sources.purge(storage, _Sources.coerce(path_or_id))
        finally:
            storage.close()


class Index:
    """Run and control background OCR indexing over registered sources.

    Not instantiated directly — use `Vethuq().index`.
    """

    def run(
        self,
        target: str | int | None = None,
        *,
        force: bool = False,
        wait: bool = False,
        languages: str | Sequence[str] | None = None,
    ) -> int | IndexState | None:
        """Start OCR indexing on registered sources in the background.

        `languages` reads the files in those languages this run (`"te"`, `"en,te"`, `"auto"`),
        instead of each source's own languages or the `settings.ocr.languages` setting.

        A source that's already fully indexed is still checked for files
        added or modified since the last run; unchanged files are left
        untouched. Returns the background process id, or, if `wait` is
        True, blocks until the run finishes and returns its final
        `IndexState` instead.

        Raises `AlreadyRunningError` if a run is already in progress, and
        `StaleLockError` if a previous run left a stale lock (`force=True`
        clears it). Raises `SourceNotFoundError` if `target` doesn't match a
        registered source, `LanguageUnavailableError` for a language that isn't installed
        or enabled, and `OcrModelMissingError` if the files would be read in a language
        whose models aren't downloaded (`ocr.models.download`).
        """
        pid = _IndexRunner.start_run(
            str(target) if target is not None else None,
            force=force,
            restart=False,
            languages=_language_value(languages),
        )
        return _IndexRunner.wait(pid) if wait else pid

    def restart(
        self,
        target: str | int | None = None,
        *,
        force: bool = False,
        wait: bool = False,
        languages: str | Sequence[str] | None = None,
    ) -> int | IndexState | None:
        """Retry only previously-failed files, in the background. See `run`."""
        pid = _IndexRunner.start_run(
            str(target) if target is not None else None,
            force=force,
            restart=True,
            languages=_language_value(languages),
        )
        return _IndexRunner.wait(pid) if wait else pid

    def reindex(
        self,
        target: str | int,
        *,
        force: bool = False,
        wait: bool = False,
        languages: str | Sequence[str] | None = None,
    ) -> int | IndexState | None:
        """Re-index every file under a source (id or path), not just failed ones.

        Files are OCR'd again and their existing documents updated in place, so
        nothing is duplicated. `languages` reads them in those languages this time; to make
        it lasting use `sources.set_languages`. Same errors and return value as `run`.
        """
        pid = _Reindex.start_source(target, force=force, languages=_language_value(languages))
        return _IndexRunner.wait(pid) if wait else pid

    def reindex_file(
        self,
        file: str | int,
        *,
        source: str | int | None = None,
        force: bool = False,
        wait: bool = False,
        languages: str | Sequence[str] | None = None,
    ) -> int | IndexState | None:
        """Re-index one file, given its document id or path.

        `languages` reads it in those languages this time - the way to redo a file whose
        language was detected wrongly.

        Raises `FileNotTrackedError` if the file isn't tracked, and
        `AmbiguousFileError` if it sits under more than one source and `source`
        (id or path) isn't given. Otherwise like `run`.
        """
        pid = _Reindex.start_file(
            file, source=source, force=force, languages=_language_value(languages)
        )
        return _IndexRunner.wait(pid) if wait else pid

    def rebuild_search(
        self, *, on_progress: Callable[[str, int, int], None] | None = None
    ) -> SearchIndexRebuildResult:
        """Rebuild the full-text search tables from the page text already stored.

        No file is re-read or re-OCR'd. `on_progress(index, position, total)` is
        called before each table is rebuilt. A table that fails is reported in the
        result's `failed` and the others still rebuild. Raises `AlreadyRunningError`
        while an index run is active.
        """
        return _SearchIndexRebuild.run(on_progress=on_progress)

    def status(self, target: str | int | None = None) -> IndexState | list[DocumentResult] | None:
        """Show background index run progress, or per-file detail for one source.

        With no `target`, returns the live/last-known `IndexState` (or None
        if no run has ever started). With a `target` (source id or path),
        returns a `DocumentResult` per file indexed under that source.
        Raises `SourceNotFoundError` if `target` doesn't match a registered
        source.
        """
        if target is None:
            return _IndexRunner.read_state()

        storage = _open_storage()
        try:
            source = _Sources.get(storage, _Sources.coerce(target))
            return _Document.get_results(storage, source.id)
        finally:
            storage.close()

    def stop(self) -> None:
        """Stop the currently running background index and wait for confirmation.

        Raises `IndexRunnerError` if no background index run is currently running.
        """
        _IndexRunner.request_stop()

    def pause(self) -> None:
        """Pause the currently running background index.

        Raises `IndexRunnerError` if no background index run is currently running.
        """
        _IndexRunner.request_pause()

    def resume(self) -> None:
        """Resume a paused background index run.

        Raises `IndexRunnerError` if no background index run is currently running.
        """
        _IndexRunner.request_resume()

    def history(self, target: str | int | None = None, limit: int = 10) -> list[IndexRun]:
        """List past background index runs, most recent first, optionally filtered to one source.

        A run over "all sources" is included alongside runs targeted at
        just `target`. Raises `SourceNotFoundError` if `target` doesn't
        match a registered source.
        """
        storage = _open_storage()
        try:
            if target is not None:
                _Sources.get(storage, _Sources.coerce(target))
            return _IndexRunner.list_runs(
                storage, str(target) if target is not None else None, limit
            )
        finally:
            storage.close()


