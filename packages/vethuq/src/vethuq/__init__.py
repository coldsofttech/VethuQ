class Search:
    """Search previously OCR-indexed content.

    Not instantiated directly — use `Vethuq().search`.
    """

    def run(
        self,
        content: str,
        *,
        context_chars: int | None = None,
        engine: str | None = None,
        case_sensitive: bool | None = None,
        threshold: float | str | None = None,
        distance: int | str | None = None,
        leet_level: str | None = None,
        noise: str | None = None,
        unicode: str | None = None,
    ) -> list[SearchMatch]:
        """Search indexed OCR text for `content`.

        Returns one `SearchMatch` per occurrence, ordered by file path
        (pages of the same PDF stay in page order, occurrences within a
        page in text order) - or best match first for the `full-text`, `fuzzy`, `proximity`,
        and `noise-fuzzy` engines. Only successfully indexed documents are considered.
        `context_chars` defaults to `Vethuq().settings.search.snippet` if not given.

        `engine` is one of `SEARCH_ENGINES` and defaults to
        `Vethuq().settings.search.engine`: `like` finds `content` anywhere,
        even inside a word, ignoring case; `exact` finds it as typed - same
        case, as a whole word; `full-text` finds pages containing its words
        (any case, English word forms such as plurals; quote a "phrase", end
        a word with * for a prefix), best matches first; `fuzzy` finds words
        close to `content`'s - typos and OCR misreads such as `Musuem` or
        `Museurn` for `Museum` - closest first (words under 4 letters and
        anything with a digit must match exactly); with `leet_level` (`"off"`, `"basic"`,
        `"standard"` or `"extended"`, defaulting to `Vethuq().settings.search.normalize.leetspeak`
        - off for `like` unless that says otherwise) `like` reads look-alike characters as the
        letters they stand for - `h3ll0` or `p@55w0rd` for `hello` or `password`, and the other
        way round (a query too short or letterless to have look-alikes is searched as it is, and
        `SearchMatch.score` is the share of it matched as typed); `noise-fuzzy` finds
        `content`'s characters hidden by stray punctuation or whitespace (letters are never
        noise), look-alike symbols and typos at once - `h..e llo`, `h @ 3 l l 0` and `helo`
        for `hello` - closest first (it uses `threshold` and `leet_level` too, and `noise`, one of
        `SEARCH_NOISE_LEVELS`, says how much noise is skipped, defaulting to
        `Vethuq().settings.search.noise_fuzzy.noise`). `unicode` (`"off"`, `"basic"` or `"full"`,
        defaulting to `Vethuq().settings.search.normalize.unicode`, which is off unless set)
        treats characters written differently as the same - `"full"` folds accents and
        compatibility forms, so `cafe` finds `café` - for `like`, `fuzzy` and `noise-fuzzy`, and
        for `exact` only when passed here; the other engines raise `SearchOptionError`. A search
        with it on reads every page rather than using the text indexes. `case_sensitive`
        defaults to `Vethuq().settings.search.normalize.case` and only `like`,
        `lexical`, `fuzzy` and `noise-fuzzy` act on it - `exact` is always case-sensitive and
        `full-text` and `proximity` never are. `threshold` (`fuzzy` and `noise-fuzzy` only)
        is the minimum similarity between `content`'s words and the words found: a
        name from `SEARCH_FUZZY_PRESETS`, a percentage (`"80%"`) or a number above 0
        and up to 1, defaulting to `Vethuq().settings.search.fuzzy.threshold`.
        `proximity` finds passages where all of `content`'s terms - at least two words
        or `"quoted phrases"`, in any order - sit within `distance` words of each other
        (`distance` is the most words between the first and last term): a name from
        `SEARCH_PROXIMITY_PRESETS` or a number from 1 to `SEARCH_PROXIMITY_MAX_DISTANCE`,
        defaulting to `Vethuq().settings.search.proximity.distance`; one
        `SearchMatch` per passage. `engine="all"` - the default, unless
        `Vethuq().settings.search.engine` says otherwise - runs every engine and returns
        the hits in ranked page order, each labelled with the engine that found it
        (see `run_pages` for them grouped by page); the options above then reach
        the engines that can use them and are never rejected. Raises `SearchOptionError`
        for an unknown engine, an invalid `threshold`, `distance`, `leet_level`, `noise` or
        `unicode`, or an explicit `case_sensitive`, `threshold`, `distance`, `leet_level`,
        `noise` or `unicode` the engine can't honour, and
        `SearchQueryError` for a `proximity` query of fewer than two terms.
        """
        storage = _open_storage()
        try:
            options = _Search.resolve_options(
                storage, engine, case_sensitive, threshold, distance, leet_level, noise, unicode
            )
            return _Search.indexed_content(
                storage,
                content,
                context_chars=context_chars,
                engine=options.engine,
                case_sensitive=options.case_sensitive,
                threshold=options.threshold,
                distance=options.distance,
                level=options.level,
                noise=options.noise,
                unicode=options.unicode,
            )
        finally:
            storage.close()

    def run_pages(
        self,
        content: str,
        *,
        context_chars: int | None = None,
        case_sensitive: bool | None = None,
        threshold: float | str | None = None,
        distance: int | str | None = None,
        leet_level: str | None = None,
        noise: str | None = None,
        unicode: str | None = None,
    ) -> list[PageResult]:
        """Search with every engine at once and return the pages found, best first.

        Each page is one `PageResult` - however many engines found it - ranked by the
        strictest engine that did: Exact, Contains, Relevant, Near, Word, Similar,
        then Obscured (see `ENGINE_TIERS` and `ENGINE_BADGES`, and `engine_badge`/`hit_badge`
        for the labels the CLI and the UI show), and within a tier by that engine's own signal.
        `PageResult.engine` is the page's strictest engine and `matched_by` all of
        them; its `hits` are `SearchMatch`es best first, each with its own `engine`
        and `matched_by` (hits found by several engines are merged into one). A hit that needed
        a normalization to match as typed carries it in `modifiers` (`"look-alike"`, `"accents"`;
        see `ENGINE_MODIFIERS`), ranks below those matched as typed, and `hit_badge` shows it
        (`Contains · look-alike`); so does `PageResult.modifiers`.

        `case_sensitive`, `threshold`, `distance`, `leet_level` and `noise` default to their
        settings and reach the engines that can use them (`like`/`lexical`/
        `fuzzy`/`noise-fuzzy`, `fuzzy`/`noise-fuzzy`, `proximity`, `like`/`noise-fuzzy`,
        `noise-fuzzy`);
        `proximity` is skipped for a query of fewer than two terms.
        `context_chars` defaults to `Vethuq().settings.search.snippet`. Raises
        `SearchOptionError` for an invalid `threshold`, `distance`, `leet_level`, `noise` or
        `unicode`. This is what `run` does when `engine="all"` (the default), with the hits
        flattened.
        """
        storage = _open_storage()
        try:
            options = _Search.resolve_options(
                storage, "all", case_sensitive, threshold, distance, leet_level, noise, unicode
            )
            return _Search.indexed_pages(
                storage,
                content,
                context_chars=context_chars,
                case_sensitive=options.case_sensitive,
                threshold=options.threshold,
                distance=options.distance,
                level=options.level,
                noise=options.noise,
                unicode=options.unicode,
            )
        finally:
            storage.close()

    def export(
        self,
        matches: list[SearchMatch],
        query: str,
        output: str | Path,
        format_: str | None = None,
        *,
        engine: str | None = None,
        case_sensitive: bool = False,
        threshold: float | None = None,
        distance: int | None = None,
        leet_level: str | None = None,
        noise: str | None = None,
        unicode: str | None = None,
    ) -> Path:
        """Write `matches` for `query` to `output` as JSON or HTML.

        `format_` defaults to `Vethuq().settings.search.export_format` if
        not given, and must be one of `SEARCH_EXPORT_FORMATS`. Pass the
        `engine`, `case_sensitive` and (for `fuzzy` or
        `proximity`) `threshold` or `distance`, (for `like` or `noise-fuzzy`) `leet_level`, or (for
        `noise-fuzzy`) `noise`, or a `unicode` level other than off, the search ran with to record
        them
        in the file.
        """
        storage = _open_storage()
        try:
            resolved_format = _SearchSettings.resolve_export_format(storage, format_)
        finally:
            storage.close()
        output_path = Path(output)
        _Export.search_results(
            matches,
            query,
            output_path,
            resolved_format,
            engine=engine,
            case_sensitive=case_sensitive,
            threshold=threshold,
            distance=distance,
            level=leet_level,
            noise=noise,
            unicode=unicode,
        )
        return output_path


class Logs:
    """Read VethuQ's log files.

    Not instantiated directly — use `Vethuq().logs`.
    """

    def tail(
        self,
        component: str,
        lines: int = 40,
        *,
        level: str | None = None,
        day: date | None = None,
    ) -> list[str]:
        """The most recent `lines` entries of a component's log, oldest first.

        `component` is one of `LOG_COMPONENTS` (`"database"`, `"index"`, `"ui"`,
        `"cli"`). `level` keeps only entries at or above it (one of
        `LOG_LEVEL_VALUES`); `day` reads that day's rotated log instead of
        today's. An entry is one log line plus any traceback lines under it.

        Raises `LogNotFoundError` if there is no log for that day and
        `ValueError` for an unknown component or level, or `lines` below 1.
        """
        return _Logs.tail(component, _default_db_path(), lines=lines, level=level, day=day)


class Db:
    """Database maintenance. Not instantiated directly — use `Vethuq().db`."""

    def integrity_check(self) -> IntegrityCheckResult:
        """Run `PRAGMA integrity_check` now and return the result.

        Also logged via the standard `logging` module (info on success,
        error with the specific corruption messages on failure). See
        `Vethuq().settings.db.integrity_check` to control whether this
        also runs automatically when the database is opened.
        """
        storage = _open_storage()
        try:
            return _IntegrityCheck.run(storage)
        finally:
            storage.close()

    def backup_create(self, name: str | None = None) -> BackupInfo:
        """Take a compressed backup of the database now and return it.

        A named snapshot is never deleted automatically. Raises `BackupError` if the
        name is invalid or taken, or the database fails its integrity check.
        """
        return _Backup.create(_default_db_path(), name)

    def backup_list(self) -> list[BackupInfo]:
        """Every database backup, newest first."""
        return _Backup.entries(_default_db_path())

    def backup_delete(self, name: str) -> None:
        """Delete one backup by name. Raises `BackupError` if there is none."""
        _Backup.delete(_default_db_path(), name)

    def restore(self, name_or_path: str) -> BackupInfo | None:
        """Replace the database with a backup (by name, or the path of a `.db.gz` file).

        The backup is verified first, and the current database is saved as a
        'safety' backup, which is returned. Raises `BackupError` on any problem,
        or `IndexRunnerError` if an index run is active.
        """
        self._require_idle()
        return _Backup.restore(_default_db_path(), name_or_path)

    def reset(self) -> BackupInfo | None:
        """Delete the database and all its data (a fresh one is created on next use).

        The current database is saved as a 'safety' backup first, which is returned.
        Raises `IndexRunnerError` if an index run is active.
        """
        self._require_idle()
        return _Backup.reset(_default_db_path())

    def repair(self) -> IntegrityCheckResult:
        """Rebuild the database's indexes (`REINDEX`) and return the fresh integrity result.

        Fixes index-only corruption; if `ok` is still False, restore a backup or
        reset. Raises `IndexRunnerError` if an index run is active.
        """
        self._require_idle()
        result, _ = _Backup.repair(_default_db_path())
        return result

    @staticmethod
    def _require_idle() -> None:
        if _IndexRunner.is_running(_default_db_path())[0]:
            raise IndexRunnerError("An index run is in progress; stop it first.")


class FileTypes:
    """Which file types this install can read (`client.file_types`)."""

    def list(self, include_missing: bool = False) -> list[FileTypeInfo]:
        """The installed file types; `include_missing` also lists those that are not installed.

        Each `FileTypeInfo` says whether the type is `installed` and `enabled`, and for a type
        that is not installed carries the `pip install` command in `install_hint`. To add or
        remove a type, install or reinstall the package (or re-run the Windows installer).
        """
        return _FileTypes.infos(include_missing=include_missing)


def _language_value(languages: str | Sequence[str] | None) -> str | None:
    """A language choice as the comma-separated string the runner takes, or None."""
    if languages is None or isinstance(languages, str):
        return languages
    return ",".join(languages)


class OcrModelsApi:
    """The OCR models each language needs on disk, like `vethuq ocr models`. Not instantiated
    directly — use `Vethuq().ocr.models`."""

    @staticmethod
    def _ids(languages: str | Sequence[str] | None) -> list[str]:
        value = _language_value(languages)
        if value is None or value.strip().lower() == "auto":
            return _Languages.enabled_ids()
        return [part.strip() for part in value.split(",") if part.strip()]

    def status(self, languages: str | Sequence[str] | None = None) -> list[ModelStatus]:
        """The models `languages` need (default: every enabled language) and which are
        downloaded; models every language shares come first."""
        return _OcrModels.status(self._ids(languages))

    def download(
        self,
        languages: str | Sequence[str] | None = None,
        *,
        force: bool = False,
        on_progress: Callable[[str, str], None] | None = None,
    ) -> DownloadResult:
        """Download the models `languages` need that are missing (all of them with `force`).

        `on_progress(model, state)` is called with `"downloading"`, `"ready"` or `"failed"`.
        Needs the internet; a model that fails is in `DownloadResult.failed` and the rest still
        download.
        """
        return _OcrModels.download(self._ids(languages), force=force, on_progress=on_progress)

    def clear(self, languages: str | Sequence[str], *, include_shared: bool = False) -> ClearResult:
        """Delete the downloaded models of `languages`; the models every language shares stay
        unless `include_shared`."""
        return _OcrModels.clear(self._ids(languages), include_shared=include_shared)

    def reset(self, languages: str | Sequence[str]) -> DownloadResult:
        """Delete `languages`' own models and download them again."""
        ids = self._ids(languages)
        _OcrModels.clear(ids)
        return _OcrModels.download(ids)

    def clean(self) -> CleanResult:
        """Remove models no enabled language uses and leftover empty download folders. Other
        programs' models in the same cache are never touched."""
        return _OcrModels.clean(_Languages.enabled_ids())


class Ocr:
    """OCR information. Not instantiated directly — use `Vethuq().ocr`."""

    def __init__(self) -> None:
        self.models = OcrModelsApi()

    def languages(self) -> list[str]:
        """The ids of the OCR languages that can be used now (installed and enabled), English
        first."""
        return _Languages.enabled_ids()


class Vethuq:
    """Client for VethuQ's local database — the same one the CLI and desktop app use.

    ```python
    client = vethuq.Vethuq()
    client.sources.add("./path/to/folder-or-file")
    client.index.run(wait=True)
    client.settings.gpu.enable()
    client.stats.processing()
    client.search.run("invoice")
    client.file_types.list()
    client.ocr.models.download("te")
    client.version.python
    ```
    """

    def __init__(self) -> None:
        self.sources = Sources()
        self.index = Index()
        self.ocr = Ocr()
        self.settings = Settings()
        self.stats = Stats()
        self.search = Search()
        self.logs = Logs()
        self.db = Db()
        self.file_types = FileTypes()

    @property
    def version(self) -> VersionDetails:
        """The VethuQ version, Python version, platform and database schema in use."""
        return _VersionInfo.details()
