class Sources:
    """Register and manage files/folders as OCR/indexing sources.

    Not instantiated directly — use `Vethuq().sources`.
    """

    def add(self, path: str | Path) -> Source:
        """Register a file or folder as a source. Folders are indexed recursively.

        Re-adding a path that was previously removed reactivates it instead
        of failing. Raises `SourcePathError` if `path` doesn't exist, and
        `SourceAlreadyExistsError` if it's already an active source.
        """
        conn = _Db.connect()
        try:
            return _Sources.add(conn, path)
        finally:
            conn.close()

    def list(self, include_inactive: bool = False) -> list[Source]:
        """Return registered sources, most recently added first."""
        conn = _Db.connect()
        try:
            return _Sources.list_all(conn, include_inactive)
        finally:
            conn.close()

    def remove(self, path_or_id: str | Path | int) -> Source:
        """Unregister a source by id or path. Raises `SourceNotFoundError` if it doesn't exist."""
        conn = _Db.connect()
        try:
            return _Sources.remove(conn, path_or_id)
        finally:
            conn.close()


class Index:
    """Run and control background OCR indexing over registered sources.

    Not instantiated directly — use `Vethuq().index`.
    """

    def run(
        self, target: str | int | None = None, *, force: bool = False, wait: bool = False
    ) -> int | IndexState | None:
        """Start OCR indexing on registered sources in the background.

        A source that's already fully indexed is still checked for files
        added or modified since the last run; unchanged files are left
        untouched. Returns the background process id, or, if `wait` is
        True, blocks until the run finishes and returns its final
        `IndexState` instead.

        Raises `AlreadyRunningError` if a run is already in progress, and
        `StaleLockError` if a previous run left a stale lock (`force=True`
        clears it). Raises `SourceNotFoundError` if `target` doesn't match a
        registered source.
        """
        pid = _IndexRunner.start_run(
            str(target) if target is not None else None, force=force, restart=False
        )
        return _IndexRunner.wait(pid) if wait else pid

    def restart(
        self, target: str | int | None = None, *, force: bool = False, wait: bool = False
    ) -> int | IndexState | None:
        """Retry only previously-failed files, in the background. See `run`."""
        pid = _IndexRunner.start_run(
            str(target) if target is not None else None, force=force, restart=True
        )
        return _IndexRunner.wait(pid) if wait else pid

    def status(self, target: str | int | None = None) -> IndexState | list[DocumentResult] | None:
        """Show background index run progress, or per-file detail for one source.

        With no `target`, returns the live/last-known `IndexState` (or None
        if no run has ever started). With a `target` (source id or path),
        returns a `DocumentResult` per file indexed under that source.
        Raises `SourceNotFoundError` if `target` doesn't match a registered
        source.
        """
        if target is None:
            return _IndexRunner.read_state()

        conn = _Db.connect()
        try:
            source = _Sources.get(conn, _Sources.coerce(target))
            return _Document.get_results(conn, source.id)
        finally:
            conn.close()

    def stop(self) -> None:
        """Stop the currently running background index and wait for confirmation.

        Raises `IndexRunnerError` if no background index run is currently running.
        """
        _IndexRunner.request_stop()

    def pause(self) -> None:
        """Pause the currently running background index.

        Raises `IndexRunnerError` if no background index run is currently running.
        """
        _IndexRunner.request_pause()

    def resume(self) -> None:
        """Resume a paused background index run.

        Raises `IndexRunnerError` if no background index run is currently running.
        """
        _IndexRunner.request_resume()

    def history(self, target: str | int | None = None, limit: int = 10) -> list[IndexRun]:
        """List past background index runs, most recent first, optionally filtered to one source.

        A run over "all sources" is included alongside runs targeted at
        just `target`. Raises `SourceNotFoundError` if `target` doesn't
        match a registered source.
        """
        conn = _Db.connect()
        try:
            if target is not None:
                _Sources.get(conn, _Sources.coerce(target))
            return _IndexRunner.list_runs(conn, str(target) if target is not None else None, limit)
        finally:
            conn.close()


class GPUSettings:
    """Whether OCR should attempt to use the GPU.

    Not instantiated directly — use `Vethuq().settings.gpu`.
    """

    def is_enabled(self) -> bool:
        """Whether OCR should attempt to use the GPU. Disabled by default."""
        conn = _Db.connect()
        try:
            return _GpuSettings.is_enabled(conn)
        finally:
            conn.close()

    def enable(self) -> None:
        """Enable GPU use for OCR.

        Only takes effect if a CUDA-capable PaddlePaddle build with a
        visible GPU is actually installed - otherwise OCR silently falls
        back to CPU.
        """
        conn = _Db.connect()
        try:
            _GpuSettings.set_enabled(conn, True)
        finally:
            conn.close()

    def disable(self) -> None:
        """Disable GPU use for OCR (the default) - OCR always runs on CPU."""
        conn = _Db.connect()
        try:
            _GpuSettings.set_enabled(conn, False)
        finally:
            conn.close()


